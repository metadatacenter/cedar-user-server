import java.util.Map;

import static org.metadatacenter.constant.CedarPathParameters.PP_ID;
import static org.metadatacenter.rest.assertion.GenericAssertions.LoggedIn;

@Path("/users")
@Produces(MediaType.APPLICATION_JSON)
public class UsersResource extends AbstractUserServerResource {

  private static final int MAX_API_KEYS = 20;

  private static UserService userService;
  private KeycloakUtilInfo kcInfo;
  private Keycloak kc;

  public UsersResource(CedarConfig cedarConfig) {
    super(cedarConfig);
    kcInfo = KeycloakUtils.initKeycloak(cedarConfig);
    kc = KeycloakUtils.buildKeycloak(kcInfo);
  }

  public static void injectUserService(UserService us) {
    userService = us;
  }

  @GET
  @Timed
  @Path("/{id}")
  public Response findOwnUser(@PathParam(PP_ID) String uuid) throws CedarException {
    CedarRequestContext c = buildRequestContext();

    c.must(c.user()).be(LoggedIn);

    CedarUser currentUser = c.getCedarUser();

    String id = linkedDataUtil.getUserId(uuid);

    if (!id.equals(currentUser.getId())) {
      return CedarResponse.forbidden()
          .id(id)
          .errorKey(CedarErrorKey.READ_OTHER_PROFILE_FORBIDDEN)
          .errorMessage("You are not allowed to read other user's profile!")
          .parameter("currentUserId", currentUser.getId())
          .build();
    }

    JsonNode user = JsonMapper.MAPPER.valueToTree(currentUser);
    // Remove autogenerated _id field to avoid exposing it
    MongoUtils.removeIdField(user);

    return Response.ok().entity(user).build();
  }

  @GET
  @Timed
  @Path("/{id}/summary")
  public Response findUserSummary(@PathParam(PP_ID) String uuid) throws CedarException {
    CedarRequestContext c = buildRequestContext();

    c.must(c.user()).be(LoggedIn);

    String id = linkedDataUtil.getUserId(uuid);
    CedarUser currentUser = c.getCedarUser();

    // Self, or a user administrator. USER_READ belongs to the userAdministrator role, which the
    // built-in admin holds and an ordinary user does not, so this admits the provenance display-name
    // lookup UserSummaryCache makes as the admin while refusing one user's summary to another. The
    // summary carries each federated identity provider together with the account id held there,
    // which is the user's identifier at Google or ORCID.
    if (!id.equals(currentUser.getId()) && !currentUser.has(CedarPermission.USER_READ)) {
      return CedarResponse.forbidden()
          .id(id)
          .errorKey(CedarErrorKey.READ_OTHER_PROFILE_FORBIDDEN)
          .errorMessage("You are not allowed to read other user's profile!")
          .parameter("currentUserId", currentUser.getId())
          .build();
    }

    CedarUserId uid = CedarUserId.build(id);

    CedarUser lookupUser = userService.findUser(uid);
    // An id CEDAR does not hold produced a 200 carrying a null screen name, since getDisplayName
    // answers null for a null user.
    if (lookupUser == null) {
      return CedarResponse.notFound()
          .id(id)
          .errorKey(CedarErrorKey.USER_NOT_FOUND)
          .errorMessage("The user can not be found by id!")
          .build();
    }

    UserRepresentation keyCloakUserRepresentation;
    try {
      UserResource userResource = kc.realm(kcInfo.getKeycloakRealmName()).users().get(uuid);
      keyCloakUserRepresentation = userResource.toRepresentation();
    } catch (NotFoundException e) {
      // Keycloak reports an unknown user by throwing, which left through the generic mapper as a
      // bare 404 carrying no CEDAR error body.
      return CedarResponse.notFound()
          .id(id)
          .errorKey(CedarErrorKey.USER_NOT_FOUND)
          .errorMessage("The user can not be found by id!")
          .build();
    } catch (ProcessingException e) {
      throw new CedarDependencyUnavailableException("Keycloak is unavailable", e);
    }

    Map<String, Object> summary = new HashMap<>();
    summary.put("userId", id);
    summary.put("screenName", CedarUserNameUtil.getDisplayName(cedarConfig, lookupUser));
    // Keycloak account creation time (epoch millis) - used as "Member since" on the profile page.
    summary.put("createdTimestamp", keyCloakUserRepresentation.getCreatedTimestamp());

    if (keyCloakUserRepresentation.getFederatedIdentities() != null) {
      List<Object> authenticationProviders = new ArrayList<>();

      for (FederatedIdentityRepresentation federatedIdentityRepresentation : keyCloakUserRepresentation.getFederatedIdentities()) {
        Map<String, String> authenticationProviderUserPair = new HashMap<>();
        String authenticationProvider = federatedIdentityRepresentation.getIdentityProvider();
        String userID = federatedIdentityRepresentation.getUserId();

        authenticationProviderUserPair.put("name", authenticationProvider);
        authenticationProviderUserPair.put("id", userID);
        authenticationProviders.add(authenticationProviderUserPair);
      }
      summary.put("authenticationProvider", authenticationProviders);
    }

    return Response.ok().entity(summary).build();
  }

  @PUT
  @Timed
  @Path("/{id}")
  public Response updateUser(@PathParam(PP_ID) String uuid) throws CedarException {
    CedarRequestContext c = buildRequestContext();

    c.must(c.user()).be(LoggedIn);

    CedarUser currentUser = c.getCedarUser();

    String id = linkedDataUtil.getUserId(uuid);

    if (!id.equals(currentUser.getId())) {
      return CedarResponse.forbidden()
          .id(id)
          .errorKey(CedarErrorKey.UPDATE_OTHER_PROFILE_FORBIDDEN)
          .errorMessage("You are not allowed to update other user's profile!")
          .parameter("currentUserId", currentUser.getId())
          .build();
    }

    JsonNode modifications = c.request().getRequestBody().asJson();

    BackendCallResult<CedarUser> cedarUserBackendCallResult = userService.patchUser(CedarUserId.build(id), modifications);
    if (cedarUserBackendCallResult.isError()) {
      return CedarResponse.from(cedarUserBackendCallResult);
    } else {
      CedarUser updatedUser = cedarUserBackendCallResult.getPayload();

      JsonNode updatedUserNode = JsonMapper.MAPPER.valueToTree(updatedUser);
      // Remove autogenerated _id field to avoid exposing it
      MongoUtils.removeIdField(updatedUserNode);

      return Response.ok().entity(updatedUserNode).build();
    }
  }

  /**
   * Creates a new CEDAR API key for the current user.
   * <p>
   * The optional JSON body may carry a {@code description}; when it is missing or blank a default
   * description carrying today's date is used. A user may hold up to {@link #MAX_API_KEYS} keys.
   * <p>
   * Self-only.
   */
  @POST
  @Timed
  @Path("/{id}/api-keys")
  public Response createApiKey(@PathParam(PP_ID) String uuid) throws CedarException {
    CedarRequestContext c = buildRequestContext();
    c.must(c.user()).be(LoggedIn);

    CedarUser currentUser = c.getCedarUser();
    Response forbidden = forbiddenIfNotSelf(uuid, currentUser);
    if (forbidden != null) {
      return forbidden;
    }

    String description = null;
    JsonNode body = c.request().getRequestBody().asJson();
    if (body != null && body.hasNonNull("description")) {
      String candidate = body.get("description").asText().trim();
      if (!candidate.isEmpty()) {
        description = candidate;
      }
    }
    if (description == null) {
      description = "API key created on " + LocalDate.now();
    }

    CedarUserApiKey newApiKey = new CedarUserApiKey();
    newApiKey.setKey(generateRandomApiKey());
    newApiKey.setServiceName("CEDAR");
    newApiKey.setDescription(description);
    newApiKey.setCreationDate(LocalDateTime.now());
    newApiKey.setEnabled(true);

    // The ceiling is checked where the keys are written, not here. Checked against the copy this
    // request holds, it could pass while another request was adding a key of its own.
    return respond(userService.addApiKey(CedarUserId.build(currentUser.getId()), newApiKey, MAX_API_KEYS));
  }

  /**
   * Regenerates a single API key: the key identified by {@code key} in the path keeps its
   * description / service name / enabled flag but gets a brand new, random value (and a fresh
   * creation date), so the old value is immediately revoked. The key count is unchanged, so this
   * is always safe - it is the way to "rotate" the last remaining key without dropping below one.
   * <p>
   * Self-only.
   */
  @POST
  @Timed
  @Path("/{id}/api-keys/{key}/regenerate")
  public Response regenerateApiKey(@PathParam(PP_ID) String uuid, @PathParam("key") String key) throws CedarException {
    CedarRequestContext c = buildRequestContext();
    c.must(c.user()).be(LoggedIn);

    CedarUser currentUser = c.getCedarUser();
    Response forbidden = forbiddenIfNotSelf(uuid, currentUser);
    if (forbidden != null) {
      return forbidden;
    }

    return respond(userService.regenerateApiKey(CedarUserId.build(currentUser.getId()), key,
        generateRandomApiKey(), LocalDateTime.now()));
  }

  /**
   * Deletes a single API key. Refused when it would leave the user with no enabled key: a user must
   * always keep at least one active key (regenerate it instead of deleting the last one). Deleting a
   * disabled key is always allowed, since a disabled key is not the account's working one.
   * <p>
   * Self-only.
   */
  @DELETE
  @Timed
  @Path("/{id}/api-keys/{key}")
  public Response deleteApiKey(@PathParam(PP_ID) String uuid, @PathParam("key") String key) throws CedarException {
    CedarRequestContext c = buildRequestContext();
    c.must(c.user()).be(LoggedIn);

    CedarUser currentUser = c.getCedarUser();
    Response forbidden = forbiddenIfNotSelf(uuid, currentUser);
    if (forbidden != null) {
      return forbidden;
    }

    // Both the lookup of the key and the "keep one active key" rule are applied where the keys are
    // written, against the stored list rather than against the copy this request holds.
    return respond(userService.deleteApiKey(CedarUserId.build(currentUser.getId()), key));
  }

  /**
   * Returns a 403 response when {@code uuid} does not identify the current user; otherwise null.
   */
  private Response forbiddenIfNotSelf(String uuid, CedarUser currentUser) {
    String id = linkedDataUtil.getUserId(uuid);
    if (!id.equals(currentUser.getId())) {
      return CedarResponse.forbidden()
          .id(id)
          .errorKey(CedarErrorKey.UPDATE_OTHER_PROFILE_FORBIDDEN)
          .errorMessage("You are not allowed to manage another user's API keys!")
          .parameter("currentUserId", currentUser.getId())
          .build();
    }
    return null;
  }

  /**
   * Renders the outcome of a key change as the updated user JSON, mirroring the shape of
   * GET /users/{id}. A refusal carries its own status and message from the layer that applied it.
   */
  private Response respond(BackendCallResult<CedarUser> callResult) {
    if (callResult.isError()) {
      return CedarResponse.from(callResult);
    }
    JsonNode updatedUserNode = JsonMapper.MAPPER.valueToTree(callResult.getPayload());
    // Remove autogenerated _id field to avoid exposing it
    MongoUtils.removeIdField(updatedUserNode);
    return Response.ok().entity(updatedUserNode).build();
  }

  /**
   * Generates a new, cryptographically-random API key rendered as 64 lowercase hex characters
   * (256 bits of entropy), matching the format of the keys CEDAR generates at user provisioning time.
   */
  private String generateRandomApiKey() {
    SecureRandom random = new SecureRandom();
    byte[] bytes = new byte[32];
    random.nextBytes(bytes);
    StringBuilder sb = new StringBuilder(64);
    for (byte b : bytes) {
      sb.append(String.format("%02x", b));
    }
    return sb.toString();
  }
}
